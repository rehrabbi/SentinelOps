// Outlines the wordmark's letters into src/brand/wordmark-path.ts, so the logo never depends on a
// font being installed or loaded. Run from frontend/ only when the wordmark's type changes:
//   node scripts/outline-wordmark.mjs
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';
import { brandFont } from './brand-board/woff2ttf.mjs';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'brand', 'wordmark-path.ts');

// U+0131 is the dotless i: its dot is drawn separately, as the diamond tittle.
const text = 'SentınelOps';
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="300"><text x="0" y="200" font-family="Space Grotesk" font-weight="600" font-size="100" letter-spacing="-2">${text}</text></svg>`;
const resvg = new Resvg(svg, { font: { fontFiles: [brandFont('Space Grotesk', 600)], loadSystemFonts: false } });

// resvg's toString() returns the normalised SVG, in which text has become paths.
const paths = [...resvg.toString().matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
if (paths.length === 0) throw new Error('no outlines produced: is Space Grotesk 600 loaded?');
const round = (n) => String(Math.round(Number(n) * 100) / 100);
const d = paths
  .join(' ')
  .replace(/-?\d+(\.\d+)?/g, round)
  .replace(/\s*([MLQCZ])\s*/g, '$1')
  .trim();

writeFileSync(
  out,
  `// Generated by scripts/outline-wordmark.mjs from Space Grotesk 600. Do not edit by hand.\n` +
    `// "Sent\u0131nelOps" at font-size 100, letter-spacing -2, from x 0 with the baseline at y 200.\n` +
    `export const WORDMARK_PATH =\n  '${d}'\n`,
);
console.log(`wrote ${out} (${d.length} characters)`);
